export function StatTile({
  label,
  value,
  hint,
  tone,
  onClick,
}: {
  label: string
  value: ReactNode
  hint?: ReactNode
  tone?: "warning" | "critical"
  onClick?: () => void
}) {
  const body = (
    <>
      <div className="flex items-center justify-between gap-2 text-[0.8125rem] font-medium text-muted-foreground">
        {label}
        {onClick && <ArrowUpRight className="size-3.5 opacity-0 transition-opacity group-hover:opacity-100 group-focus-visible:opacity-100" />}
      </div>
      <div
        className={cn(
          "mt-2 text-[1.75rem] font-semibold leading-none tracking-tight tabular-nums",
          tone === "critical" && "text-destructive",
          tone === "warning" && "text-warning"
        )}
      >
        {value}
      </div>
      {hint && <div className="mt-2 text-xs text-muted-foreground">{hint}</div>}
    </>
  )
  if (!onClick) return <div className="p-4">{body}</div>
  return (
    <button
      type="button"
      onClick={onClick}
      className="group p-4 text-left transition-colors hover:bg-accent/60 focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ring"
    >
      {body}
    </button>
  )
}

/** A chart card with a "table" toggle: every chart's values are readable without hovering. */
export function ChartCard({
  title,
  description,
  legend,
  table,
  children,
  className,
}: {
  title: string
  description?: string
  legend?: ReactNode
  table: ReactNode
  children: ReactNode
  className?: string
}) {
  const [asTable, setAsTable] = useState(false)
  return (
    <Card className={className}>
      <CardHeader className="flex flex-row items-start justify-between gap-2 p-5 pb-3">
        <div>
          <CardTitle className="text-base font-semibold text-foreground">{title}</CardTitle>
          {description && <p className="mt-0.5 text-xs text-muted-foreground">{description}</p>}
        </div>
        <Button variant="ghost" size="sm" className="text-muted-foreground" onClick={() => setAsTable((v) => !v)} aria-pressed={asTable}>
          <Table2 />
          {asTable ? "Chart" : "Table"}
        </Button>
      </CardHeader>
      <CardContent className="p-5 pt-0">
        {legend && !asTable && <div className="mb-2 flex flex-wrap gap-4 text-xs text-muted-foreground">{legend}</div>}
        {asTable ? table : children}
      </CardContent>
    </Card>
  )
}

