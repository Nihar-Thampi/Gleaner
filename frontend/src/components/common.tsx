export function DomainBadge({ status }: { status: DomainStatus | "unknown" }) {
  if (status === "unknown") return <StateBadge icon={ShieldQuestion} label="Not reviewed" className="bg-warning/15 text-warning" />
  const [icon, cls] = DOMAIN_STYLE[status]
  return <StateBadge icon={icon} label={DOMAIN_STATUS_LABELS[status]} className={cls} />
}

