/** A field's fill rate as a thin bar plus the number; below 50% is flagged. */
export function FillBar({ rate }: { rate: number }) {
  const low = rate < 0.5
  return (
    <div className="flex items-center gap-2">
      <div className="h-1.5 w-20 overflow-hidden rounded-full bg-muted">
        <div className={cn("h-full rounded-full", low ? "bg-destructive" : "bg-chart-1")} style={{ width: `${rate * 100}%` }} />
      </div>
      <span className={cn("w-10 text-right text-xs tabular-nums", low ? "font-medium text-destructive" : "text-muted-foreground")}>
        {Math.round(rate * 100)}%
      </span>
      {low && <AlertTriangle className="size-3.5 text-destructive" aria-label="Low fill rate" />}
    </div>
  )
}

export function ValueCell({ value, type }: { value: unknown; type?: FieldType }) {
  if (type === "url" && typeof value === "string" && value) {
    return (
      <a href={value} target="_blank" rel="noreferrer" className="inline-flex max-w-64 items-center gap-1 truncate text-link hover:underline">
        <span className="truncate">{value.replace(/^https?:\/\/(www\.)?/, "")}</span>
        <ExternalLink className="size-3 shrink-0" />
      </a>
    )
  }
  const text = fmtValue(value, type)
  return <span className={cn(text === "—" && "text-muted-foreground", typeof value === "number" && "tabular-nums")}>{text}</span>
}

/** "price 217.99 → 21.80 (−90%)" */
export function FieldDiff({ field, before, after, type }: { field: string; before: unknown; after: unknown; type?: FieldType }) {
  const pct = pctChange(before, after)
  return (
    <span className="inline-flex flex-wrap items-baseline gap-x-1.5 text-sm">
      <span className="font-mono text-xs text-muted-foreground">{field}</span>
      <span className="font-mono text-[0.8125rem] text-muted-foreground line-through decoration-muted-foreground/50">{fmtValue(before, type)}</span>
      <ArrowRight className="size-3 self-center text-muted-foreground" aria-label="to" />
      <span className="font-mono text-[0.8125rem] font-medium">{fmtValue(after, type)}</span>
      {pct !== null && (
        <span className="font-mono text-xs tabular-nums text-changed-ink">
          ({pct > 0 ? "+" : "−"}
          {Math.abs(pct).toFixed(Math.abs(pct) < 10 ? 1 : 0)}%)
        </span>
      )}
    </span>
  )
}

export function Pager({ total, limit, offset, onChange }: { total: number; limit: number; offset: number; onChange: (o: number) => void }) {
  if (total <= limit) return null
  return (
    <div className="flex items-center justify-between gap-2 pt-3 text-sm text-muted-foreground">
      <span>
        {offset + 1}–{Math.min(offset + limit, total)} of {total.toLocaleString()}
      </span>
      <div className="flex gap-2">
        <Button variant="outline" size="sm" disabled={offset === 0} onClick={() => onChange(Math.max(0, offset - limit))}>
          Previous
        </Button>
        <Button variant="outline" size="sm" disabled={offset + limit >= total} onClick={() => onChange(offset + limit)}>
          Next
        </Button>
      </div>
    </div>
  )
}
